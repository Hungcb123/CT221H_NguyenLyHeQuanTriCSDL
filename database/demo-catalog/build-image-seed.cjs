// Add reviewed illustrations to existing demo rows without replacing custom images.
const fs = require('node:fs');
const path = require('node:path');
const products = require('./products.json');
const quote = s => "N'" + s.replaceAll("'", "''") + "'";
let sql = `-- Generated by database/demo-catalog/build-image-seed.cjs.
USE FreshGroceryDB;
GO
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET XACT_ABORT ON;
BEGIN TRY
BEGIN TRANSACTION;
`;
for (const p of products) {
  if (!p.image) throw new Error('Missing image: ' + p.name);
  sql += `
UPDATE sp SET HinhAnh=${quote(p.image)},NgayCapNhat=GETDATE()
FROM SanPham sp
LEFT JOIN SanPham parent ON parent.MaSP=sp.MaSPCha
WHERE ((sp.MaSPCha IS NULL AND sp.TenSP=${quote(p.name)}) OR parent.TenSP=${quote(p.name)})
  AND sp.TrangThaiXoa=0 AND (sp.HinhAnh IS NULL OR LTRIM(RTRIM(sp.HinhAnh))=N'');
`;
}
sql += `
COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO
`;
fs.writeFileSync(path.join(__dirname, '../18_demo_catalog_images.sql'), sql);
console.log(`Generated image backfill for ${products.length} families and their variants.`);

const creditsPath = path.join(__dirname, '../../frontend/public/product-image-credits.html');
const sources = require('./image-sources.json');
const escape = s => String(s || '').replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const rows = sources.map(s => `<li><strong>${escape(s.name)}</strong><br>${escape((s.author || '').replace(/<[^>]*>/g, ''))} — ${escape(s.license)} · <a href="${escape(s.sourcePage)}">Nguồn ảnh</a>${s.licenseUrl ? ` · <a href="${escape(s.licenseUrl)}">Giấy phép</a>` : ''}</li>`).join('\n');
const section = `<!-- demo-catalog-start -->\n<h2>Ảnh bổ sung cho bộ demo quy cách và từ đồng nghĩa</h2>\n<ul>\n${rows}\n</ul>\n<!-- demo-catalog-end -->`;
let credits = fs.readFileSync(creditsPath, 'utf8');
if (credits.includes('<!-- demo-catalog-start -->')) credits = credits.replace(/<!-- demo-catalog-start -->[\s\S]*?<!-- demo-catalog-end -->/, section);
else credits = credits.replace('</html>', section + '\n</html>');
fs.writeFileSync(creditsPath, credits);
