// Generate repeatable SQL from the reviewed catalog; no third-party dependencies.
const fs = require('node:fs');
const path = require('node:path');
const products = JSON.parse(fs.readFileSync(path.join(__dirname, 'products.json'), 'utf8'));
const n = value => value == null ? 'NULL' : "N'" + String(value).replaceAll("'", "''") + "'";
const parents = new Set();
for (const p of products) {
  if (parents.has(p.name)) throw new Error('Duplicate product: ' + p.name);
  parents.add(p.name);
  const labels = new Set();
  for (const v of p.packs) {
    if (labels.has(v.label) || v.price <= 0 || v.stock < 0 || v.grams <= 0) throw new Error('Invalid variant: ' + p.name);
    labels.add(v.label);
  }
}
let sql = `-- Generated by database/demo-catalog/build-seed.cjs. Source: products.json.
-- Demo prices per package, not verified market prices. Re-running preserves stock/edits/deletions.
USE FreshGroceryDB;
GO
SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET XACT_ABORT ON;
BEGIN TRY
BEGIN TRANSACTION;
DECLARE @ParentId INT, @Extra NVARCHAR(MAX);
`;
for (const p of products) {
  const packs = p.packs.map(v => v.label + ' (' + v.grams + ' g)').join(', ');
  const details = `${p.use} Tên gọi khác: ${p.aliases.join(', ')}. Quy cách có sẵn: ${packs}.`;
  if (!p.existing) {
    sql += `
IF NOT EXISTS (SELECT 1 FROM SanPham WITH (UPDLOCK,HOLDLOCK) WHERE TenSP=${n(p.name)} AND MaSPCha IS NULL)
    INSERT INTO SanPham(TenSP,MoTa,HinhAnh,Gia,DonViTinh,SoLuongTon,HanSuDung,NhietDoBaoQuan,MaDanhMuc)
    VALUES(${n(p.name)},${n(details)},${n(p.image)},${p.packs[0].price},${n(p.packs[0].unit)},0,DATEADD(DAY,${p.shelfLifeDays},GETDATE()),${n(p.storage)},${p.category});
`;
  }
  sql += `
SET @ParentId=NULL;
SELECT TOP 1 @ParentId=MaSP FROM SanPham WITH (UPDLOCK,HOLDLOCK)
WHERE TenSP=${n(p.name)} AND MaSPCha IS NULL AND TrangThaiXoa=0 ORDER BY MaSP;
IF @ParentId IS NOT NULL
BEGIN
`;
  if (p.existing) sql += `    SET @Extra=${n(details)};
    UPDATE SanPham SET MoTa=CASE WHEN NULLIF(MoTa,N'') IS NULL THEN @Extra ELSE MoTa+NCHAR(10)+@Extra END,NgayCapNhat=GETDATE()
    WHERE MaSP=@ParentId AND CHARINDEX(@Extra,ISNULL(MoTa,N''))=0;
`;
  for (const v of p.packs) sql += `    IF NOT EXISTS (SELECT 1 FROM SanPham WITH (UPDLOCK,HOLDLOCK) WHERE MaSPCha=@ParentId AND TenLoai=${n(v.label)})
        INSERT INTO SanPham(MaSPCha,TenLoai,TenSP,MoTa,HinhAnh,Gia,DonViTinh,SoLuongTon,HanSuDung,NhietDoBaoQuan,MaDanhMuc)
        VALUES(@ParentId,${n(v.label)},${n(p.name+' - '+v.label)},${n(p.use+' Tên gọi khác: '+p.aliases.join(', ')+'. Quy cách: '+v.label+'. Khối lượng tham khảo '+v.grams+' g; giá tính cho một '+v.unit+'.')},${n(p.image)},${v.price},${n(v.unit)},${v.stock},DATEADD(DAY,${p.shelfLifeDays},GETDATE()),${n(p.storage)},${p.category});
`;
  sql += 'END;\n';
}
sql += `
COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO
`;
fs.writeFileSync(path.join(__dirname, '../17_demo_search_catalog.sql'), sql);
console.log(`Generated ${products.length} product families, ${products.reduce((n,p)=>n+p.packs.length,0)} variants.`);
